def main():
    root = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else ROOT_PATH
    output_file = root / "index.json"

    print(f"Indexing {root} (max depth {MAX_DEPTH})...")
    t0 = time.time()

    dirs: list = []
    files: list = []
    projects: list = []
    errors: list = []
    visited: set = set()

    traverse(root, root, 0, dirs, files, projects, errors, visited)

    elapsed_ms = round((time.time() - t0) * 1000)

    ext_counts: dict[str, int] = {}
    for f in files:
        ext_counts[f["ext"]] = ext_counts.get(f["ext"], 0) + 1
    ext_summary = sorted(
        [{"ext": k, "count": v} for k, v in ext_counts.items()],
        key=lambda x: -x["count"],
    )[:20]

    domain_summary = []
    for dk, dl in DOMAIN_LABELS.items():
        domain_summary.append({
            "id": dk,
            "label": dl,
            "project_count": sum(1 for p in projects if p.get("domain") == dk),
            "dir_count": sum(1 for d in dirs if d.get("domain") == dk),
        })

    output = {
        "generated": datetime.now(tz=timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "root": str(root),
        "scan_depth": MAX_DEPTH,
        "duration_ms": elapsed_ms,
        "total_dirs": len(dirs),
        "total_files": len(files),
        "total_projects": len(projects),
        "error_count": len(errors),
        "domains": domain_summary,
        "projects": projects,
        "extension_summary": ext_summary,
        "top_level_dirs": [d for d in dirs if d["depth"] == 0],
        "claude_aware_dirs": [
            {k: d[k] for k in ("name", "path", "depth", "domain")}
            for d in dirs if d.get("claude_aware")
        ],
        "errors": errors,
    }

    with open(output_file, "w", encoding="utf-8") as fh:
        json.dump(output, fh, indent=2, ensure_ascii=False)

    print(f"\n[OK] index.json written to: {output_file}")
    print(f"  Dirs:     {len(dirs)}")
    print(f"  Files:    {len(files)}")
    print(f"  Projects: {len(projects)}")
    print(f"  Errors:   {len(errors)}")
    print(f"  Time:     {elapsed_ms}ms")

    if errors:
        print("\nErrors during scan:")
        for e in errors:
            print(f"  [{e['type']}] {e['path']}")
        sys.exit(1)


if __name__ == "__main__":
    main()
