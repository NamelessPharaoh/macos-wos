def rel(path: Path, root: Path) -> str:
    """Return a forward-slash relative path string."""
    try:
        return path.relative_to(root).as_posix()
    except ValueError:
        return str(path)


def safe_stat(path: Path) -> dict:
    """Return size_kb and last_modified without raising on permission errors."""
    try:
        s = path.stat()
        return {
            "size_kb": round(s.st_size / 1024, 2),
            "last_modified": datetime.fromtimestamp(s.st_mtime, tz=timezone.utc).strftime(
                "%Y-%m-%dT%H:%M:%SZ"
            ),
        }
    except OSError:
        return {"size_kb": 0, "last_modified": ""}


def parse_package_json(path: Path) -> dict | None:
    """Extract name, version, framework, and top scripts from package.json."""
    try:
        data = json.loads(path.read_text(encoding="utf-8", errors="replace"))
        deps = {**data.get("dependencies", {}), **data.get("devDependencies", {})}
        framework = ""
        if "next" in deps:
            framework = f"Next.js {deps['next'].lstrip('^~')}"
        elif "@nestjs/core" in deps:
            framework = f"NestJS {deps['@nestjs/core'].lstrip('^~')}"
        elif "react" in deps:
            framework = f"React {deps['react'].lstrip('^~')}"
        elif "express" in deps:
            framework = f"Express {deps['express'].lstrip('^~')}"
        return {
            "name": data.get("name", ""),
            "version": data.get("version", ""),
            "framework": framework,
            "scripts": list(data.get("scripts", {}).keys())[:8],
            "top_deps": list(deps.keys())[:5],
        }
    except Exception:
        return None


def parse_pyproject(path: Path) -> dict | None:
    """Minimal pyproject.toml parser (no external deps required)."""
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
        name = ""
        for line in text.splitlines():
            if line.strip().startswith("name"):
                name = line.split("=", 1)[-1].strip().strip('"\'')
                break
        framework = ""
        if "fastapi" in text.lower():
            framework = "FastAPI"
        elif "flask" in text.lower():
            framework = "Flask"
        elif "django" in text.lower():
            framework = "Django"
        return {"name": name, "framework": framework}
    except Exception:
        return None


