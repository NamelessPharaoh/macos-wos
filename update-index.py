def traverse(
    path: Path,
    root: Path,
    depth: int,
    dirs_out: list,
    files_out: list,
    projects_out: list,
    errors_out: list,
    visited: set,
):
    if depth > MAX_DEPTH:
        return

    # Symlink loop guard
    try:
        real = path.resolve()
    except OSError:
        real = path
    if real in visited:
        return
    visited.add(real)

    try:
        children = sorted(path.iterdir())
    except PermissionError as e:
        errors_out.append({"type": "AccessDenied", "path": rel(path, root), "message": str(e)})
        return
    except OSError as e:
        errors_out.append({"type": "OSError", "path": rel(path, root), "message": str(e)})
        return

    for child in children:
        if child.is_dir():
            if child.name in SKIP_DIRS:
                continue

            stat = safe_stat(child)
            has_claude = (child / "CLAUDE.md").exists() or (child / "agent-context.md").exists()
            has_pkg = (child / "package.json").exists()
            has_git = (child / ".git").exists()
            has_pyproject = (child / "pyproject.toml").exists()
            has_deploy = any((child / f).exists() for f in DEPLOY_SIGNAL_FILES)

            pkg_meta = parse_package_json(child / "package.json") if has_pkg else None
            py_meta = parse_pyproject(child / "pyproject.toml") if has_pyproject else None

            domain_info = PROJECT_REGISTRY.get(child.name)

            dir_entry: dict = {
                "name": child.name,
                "path": rel(child, root),
                "depth": depth,
                "claude_aware": has_claude,
                "has_package_json": has_pkg,
                "has_git": has_git,
                "has_pyproject": has_pyproject,
                "has_deploy_config": has_deploy,
                "last_modified": stat["last_modified"],
                "domain": domain_info["domain"] if domain_info else None,
            }
            dirs_out.append(dir_entry)

            if domain_info:
                proj_entry = {
                    **domain_info,
                    "name": child.name,
                    "path": rel(child, root),
                    "claude_aware": has_claude,
                    "has_git": has_git,
                    "framework": (pkg_meta or py_meta or {}).get("framework", ""),
                    "pkg_name": (pkg_meta or {}).get("name", ""),
                }
                projects_out.append(proj_entry)

            traverse(child, root, depth + 1, dirs_out, files_out, projects_out, errors_out, visited)

        else:
            if child.suffix.lower() in SKIP_EXTENSIONS:
                continue
            stat = safe_stat(child)
            files_out.append({
                "name": child.name,
                "ext": child.suffix.lower(),
                "path": rel(child, root),
                "size_kb": stat["size_kb"],
                "last_modified": stat["last_modified"],
                "depth": depth,
            })


